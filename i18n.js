  // 문구를 찾아 {0}, {1} 자리에 값을 넣습니다. 없는 언어나 키는 영어, 한국어 순으로 대신합니다.
  function t(lang, key, ...args) {
    const s = (M[lang] && M[lang][key]) || M.en[key] || M.ko[key] || key;
    return s.replace(/\{(\d)\}/g, (_, i) => (args[i] == null ? "" : String(args[i])));
  }

  // data-i18n 속성이 붙은 요소에 현재 언어의 문구를 채웁니다.
  function apply(lang, root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach((e) => { e.textContent = t(lang, e.dataset.i18n); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((e) => { e.placeholder = t(lang, e.dataset.i18nPlaceholder); });
    root.querySelectorAll("[data-i18n-title]").forEach((e) => { e.title = t(lang, e.dataset.i18nTitle); });
    if (root === document) document.documentElement.lang = lang;
  }

  // 언어 선택 상자를 채웁니다. 각 언어는 그 언어의 이름으로 표시합니다.
  function fillSelect(select, lang) {
    select.textContent = "";
    for (const [code, name] of LANGS) {
      const o = document.createElement("option");
      o.value = code;
      o.textContent = name;
      select.appendChild(o);
    }
    select.value = M[lang] ? lang : "ko";
  }

  g.DTI18N = { LANGS, MESSAGES: M, t, apply, fillSelect };
